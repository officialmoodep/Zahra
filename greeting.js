/* یک متن را بر اساس «روز چندم رابطه» به‌صورت چرخشی انتخاب می‌کند */
function pickCyclic(arr, dayIndex) {
  return arr[((dayIndex % arr.length) + arr.length) % arr.length];
}

function renderGreeting() {
  const el = document.getElementById('greetingBanner');
  if (!el) return;

  const now = iranNow();
  const hour = now.getUTCHours();
  const J = gregorianToJalali(now.getUTCFullYear(), now.getUTCMonth() + 1, now.getUTCDate());
  const dayIndex = Math.floor((now - startDate) / 86400000);

  // امروز سالگرده؟ (روز/ماه میلادیِ معادل تاریخ شروع)
  const isAnniversary = J[1] === CONFIG.startJalali.m && J[2] === CONFIG.startJalali.d && J[0] > CONFIG.startJalali.y;
  // امروز ماه‌گرده؟ (همون روز از ماه میلادی، به‌جز خودِ سالگرد)
  const isMonthly = !isAnniversary && J[2] === CONFIG.startJalali.d && now - startDate > 864e5;

  let text;

  if (isAnniversary) {
    text = GREETING_DATA.anniversary;
  } else if (isMonthly) {
    const elapsed = getElapsed(startDate, now);
    text = GREETING_DATA.monthly[elapsed.months % GREETING_DATA.monthly.length];
  } else if (hour >= 6 && hour < 12) {
    text = pickCyclic(GREETING_DATA.morning, dayIndex);
  } else if (hour >= 12 && hour < 17) {
    text = pickCyclic(GREETING_DATA.noon, dayIndex);
  } else if (hour >= 17 && hour < 23) {
    text = pickCyclic(GREETING_DATA.evening, dayIndex);
  } else {
    text = pickCyclic(GREETING_DATA.night, dayIndex);
  }

  el.innerHTML = text.replace(/\n/g, '<br>');
}

renderGreeting();
setInterval(renderGreeting, 60000); // هر دقیقه چک می‌کنه بازه عوض شده یا نه
